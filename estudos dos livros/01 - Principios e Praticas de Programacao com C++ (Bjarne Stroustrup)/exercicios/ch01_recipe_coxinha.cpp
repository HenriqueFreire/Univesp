#include <iostream>

int main() {
  std::cout << "=== Brazilian Coxinha Recipe ===\n\n";

  std::cout << "1. Prepare the filling:\n";
  std::cout << "   - Cook and shred the chicken breast.\n";
  std::cout << "   - Saute with garlic, onion, and spices.\n";
  std::cout << "   - Optional: mix with cream cheese (Catupiry).\n\n";

  std::cout << "2. Make the dough:\n";
  std::cout << "   - In a pot, bring chicken broth and butter to a boil.\n";
  std::cout << "   - Add wheat flour and stir vigorously until smooth.\n";
  std::cout << "   - Let the dough cool and knead until soft.\n\n";

  std::cout << "3. Shape the coxinhas:\n";
  std::cout << "   - Take a small portion of dough and flatten it into a disc.\n";
  std::cout << "   - Place a spoonful of chicken filling in the center.\n";
  std::cout << "   - Close the dough and shape it into a teardrop (drumstick) shape.\n\n";

  std::cout << "4. Bread and fry:\n";
  std::cout << "   - Dip each coxinha in milk or beaten eggs, then coat with breadcrumbs.\n";
  std::cout << "   - Deep-fry in hot oil until golden brown and crispy.\n";
  std::cout << "   - Drain on paper towels.\n\n";

  std::cout << "5. Serve and enjoy your homemade Brazilian coxinhas!\n";
}
