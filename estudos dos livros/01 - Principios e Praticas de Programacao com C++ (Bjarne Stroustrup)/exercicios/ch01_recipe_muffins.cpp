#include <iostream>

int main() {
  std::cout << "=================================================================\n";
  std::cout << "               DETAILED HOMEMADE MUFFINS RECIPE                  \n";
  std::cout << "=================================================================\n\n";

  std::cout << "[ INGREDIENTS ]\n";
  std::cout << "  - 2 cups (250g) all-purpose flour\n";
  std::cout << "  - 1/2 cup (100g) granulated sugar\n";
  std::cout << "  - 1 tablespoon baking powder\n";
  std::cout << "  - 1/2 teaspoon salt\n";
  std::cout << "  - 1 cup (240ml) whole milk (room temperature)\n";
  std::cout << "  - 1/2 cup (115g) unsalted butter, melted and cooled\n";
  std::cout << "  - 2 large eggs (room temperature)\n";
  std::cout << "  - 1 teaspoon vanilla extract\n";
  std::cout << "  - 1 cup chocolate chips or fresh blueberries (optional)\n\n";

  std::cout << "[ EQUIPMENT ]\n";
  std::cout << "  - 12-cup muffin tin (muffin pan)\n";
  std::cout << "  - Paper muffin liners (or cooking spray)\n";
  std::cout << "  - Two large mixing bowls\n";
  std::cout << "  - Whisk and rubber spatula\n";
  std::cout << "  - Wire cooling rack\n\n";

  std::cout << "[ STEP-BY-STEP INSTRUCTIONS ]\n\n";

  std::cout << "Step 1: Preheat and Prepare\n";
  std::cout << "  - Preheat your oven to 400°F (200°C).\n";
  std::cout << "  - Line a 12-cup muffin tin with paper muffin liners, or grease lightly.\n\n";

  std::cout << "Step 2: Whisk the Dry Ingredients\n";
  std::cout << "  - In a large bowl, whisk together the flour, sugar, baking powder, and salt.\n";
  std::cout << "  - Create a well (a small hollow space) in the center of the dry mixture.\n\n";

  std::cout << "Step 3: Combine the Wet Ingredients\n";
  std::cout << "  - In a separate bowl, whisk together milk, melted butter, eggs, and vanilla extract until uniform.\n\n";

  std::cout << "Step 4: Combine Wet and Dry (The Muffin Method)\n";
  std::cout << "  - Pour the wet ingredients into the well of the dry ingredients.\n";
  std::cout << "  - Using a spatula, gently fold the mixture together until just combined.\n";
  std::cout << "  - IMPORTANT: Do not overmix! The batter should remain slightly lumpy.\n";
  std::cout << "  - Gently fold in chocolate chips or blueberries if desired.\n\n";

  std::cout << "Step 5: Fill the Muffin Tin\n";
  std::cout << "  - Spoon the batter evenly into the 12 muffin cups, filling each about 3/4 full.\n\n";

  std::cout << "Step 6: Bake\n";
  std::cout << "  - Bake at 400°F (200°C) for 18 to 20 minutes until golden brown on top.\n";
  std::cout << "  - Perform the toothpick test: insert a toothpick into the center of a muffin.\n";
  std::cout << "    If it comes out clean with no wet batter, they are done!\n\n";

  std::cout << "Step 7: Cool and Serve\n";
  std::cout << "  - Let muffins rest in the tin for 5 minutes.\n";
  std::cout << "  - Transfer them to a wire cooling rack to cool down completely.\n";
  std::cout << "  - Enjoy warm with butter or your favorite hot beverage!\n\n";

  std::cout << "=================================================================\n";
  std::cout << "                   CULINARY & ENGLISH GLOSSARY                   \n";
  std::cout << "=================================================================\n";
  std::cout << "1. Batter vs. Dough:\n";
  std::cout << "   - Batter = A pourable or spoonable mixture of flour and liquid (pancakes, cakes, muffins).\n";
  std::cout << "   - Dough  = A thick, pliable mixture that can be kneaded and rolled (bread, pizza, cookies).\n\n";

  std::cout << "2. Fold (Folding):\n";
  std::cout << "   - Gently combining ingredients using a rubber spatula in a curved, bottom-to-top motion.\n";
  std::cout << "   - Prevents gluten development and keeps the batter light and airy.\n\n";

  std::cout << "3. Overmix:\n";
  std::cout << "   - Stirring or beating ingredients excessively. For muffins, this leads to dense, rubbery textures.\n\n";

  std::cout << "4. Baking Powder vs. Baking Soda:\n";
  std::cout << "   - Baking powder = Complete leavening agent containing an acid and base (activated by moisture & heat).\n";
  std::cout << "   - Baking soda   = Pure sodium bicarbonate (requires an acidic ingredient like buttermilk or lemon juice).\n\n";

  std::cout << "5. Preheat:\n";
  std::cout << "   - Heating the oven to the target temperature before placing food inside to ensure even baking.\n\n";

  std::cout << "6. Whisk:\n";
  std::cout << "   - A wire-looped kitchen utensil (or the action of beating rapidly) to blend, aerate, and remove lumps.\n\n";

  std::cout << "7. Toothpick Test:\n";
  std::cout << "   - Inserting a clean toothpick into the center of a muffin; if it comes out clean, baking is complete.\n\n";

  std::cout << "8. Wire Cooling Rack:\n";
  std::cout << "   - A raised metal grid that allows air circulation around baked goods, preventing soggy bottoms.\n";
  std::cout << "=================================================================\n";
}
